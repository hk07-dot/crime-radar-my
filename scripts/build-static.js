// Builds the GitHub Pages site into docs/:
//   docs/index.html      the same page as public/index.html, plus the static data layer
//   docs/js/core.js      lib/heat.js and lib/route.js bundled for the browser (one source of truth)
//   docs/js/static-api.js  answers the page's /api/… calls in the browser
//   docs/data/*.json     districts, incidents and metadata
// Run: node scripts/build-static.js   (GitHub Actions runs it after collecting data)
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const out = path.join(root, 'docs');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');
const write = (f, s) => { fs.mkdirSync(path.dirname(path.join(out, f)), { recursive: true }); fs.writeFileSync(path.join(out, f), s); };

function bundleCore() {
  // A tiny CommonJS shim: lib/heat.js and lib/route.js run unchanged; './geo' is replaced by the one
  // pure function they need from it, since lib/geo.js reads and writes files.
  const mod = (name, src) => `modules[${JSON.stringify(name)}] = function (module, exports, require) {\n${src}\n};`;
  const haversine = /function haversineKm[\s\S]*?\n}\n/.exec(read('lib/geo.js'))[0];
  return `// Generated by scripts/build-static.js from lib/heat.js and lib/route.js. Don't edit; edit those.
(function () {
const process = { env: {} };
const modules = {}, cache = {};
function require(name) {
  if (!cache[name]) { const module = { exports: {} }; cache[name] = module; modules[name](module, module.exports, require); }
  return cache[name].exports;
}
${haversine}
modules['./geo'] = function (module) { module.exports = { haversineKm }; };
${mod('./heat', read('lib/heat.js'))}
${mod('./route', read('lib/route.js'))}
window.CR = { heat: require('./heat'), route: require('./route'), haversineKm };
})();
`;
}

function buildPage() {
  const html = read('public/index.html');
  const marker = '<script src="https://unpkg.com/leaflet@1.9.4/dist/leaflet.js"></script>';
  if (!html.includes(marker)) throw new Error('build-static: Leaflet script tag not found in public/index.html');
  return html.replace(marker, `${marker}\n<script src="js/core.js"></script>\n<script src="js/static-api.js"></script>`);
}

async function buildData() {
  const { getDistricts } = require('../lib/official');
  const store = require('../lib/store');
  const districts = await getDistricts();
  // Only what the page shows; everything stays as public as the sources it came from.
  const keep = ['type', 'title', 'link', 'outlet', 'source', 'verified', 'publishedAt', 'place', 'area', 'lat', 'lng', 'precision', 'alsoReported'];
  const incidents = store.load().map(i => Object.fromEntries(keep.filter(k => i[k] !== undefined).map(k => [k, i[k]])));
  const towns = Object.entries(JSON.parse(read('data/police-districts.json'))).filter(([k]) => !k.startsWith('_'))
    .map(([k, [lat, lng]]) => ({ label: k.replace(/\b\w/g, c => c.toUpperCase()), lat, lng }));
  const meta = { generatedAt: new Date().toISOString(), officialYear: districts[0]?.year, districts: districts.length, incidents: incidents.length, towns };
  write('data/districts.json', JSON.stringify(districts));
  write('data/incidents.json', JSON.stringify(incidents));
  write('data/meta.json', JSON.stringify(meta));
  return meta;
}

async function build() {
  write('index.html', buildPage());
  write('js/core.js', bundleCore());
  write('js/static-api.js', read('static/static-api.js'));
  write('.nojekyll', '');
  const meta = await buildData();
  console.log(`[build] docs/ ready: ${meta.districts} districts, ${meta.incidents} incidents, official year ${meta.officialYear}`);
  return meta;
}

if (require.main === module) build().catch(e => { console.error(e); process.exit(1); });
module.exports = { build };
